/** An envelope's validator, optional or not: `v.optional(envelope)` is a copy, so it's matched by its fields. */
const ENVELOPE_FIELDS = Object.keys((envelope as unknown as Node).fields!).join()
const isEnvelopeNode = (node: Node) => node.kind === 'object' && Object.keys(node.fields!).join() === ENVELOPE_FIELDS

/**
 * `full` sets every field, optional ones included, takes the last choice of each union and
 * non-zero values. Otherwise only required fields are set, with the first choice of each
 * union and zero values (`false`, `0`, `[]`), which a bridge host has to send as such rather
 * than leave out. `choose` overrides which choice the unions at some paths take.
 */
function sample(node: Node, path: string, full: boolean, choose = new Map<string, number>()): unknown {
  if (isEnvelopeNode(node)) return SAMPLE_ENVELOPE
  const name = path.slice(path.lastIndexOf('.') + 1).replace('[]', '')
  switch (node.kind) {
    case 'string':
      return `${name}-1`
    case 'float64':
      return full ? 1 : 0
    case 'boolean':
      return full
    case 'literal':
      return node.value
    case 'union': {
      const choices = node.members!
      const index = choose.get(path) ?? (full ? choices.length - 1 : 0)
      return sample(choices[index]!, path, full, choose)
    }
    case 'array':
      return full ? [sample(node.element!, `${path}[]`, full, choose)] : []
    case 'object': {
      const out: Record<string, unknown> = {}
      for (const [key, field] of Object.entries(node.fields!)) {
        if (full || field.isOptional === 'required')
          out[key] = sample(field, path ? `${path}.${key}` : key, full, choose)
      }
      return out
    }
    default:
      // A kind with no example yet: teach `sample` it rather than leave the field untested.
      throw new Error(`No example value for a ${node.kind} (${name})`)
  }
}

type Choice = { path: string; index: number; label: string }

/**
 * Every union in an event with every field, with its path, its choices, and the choices of
 * the unions it sits inside (`within`), which an example of it has to take to reach it.
 */
function unionsOf(
  node: Node,
  path: string,
  within: Choice[] = [],
  out: { path: string; choices: Node[]; within: Choice[] }[] = [],
) {
  if (isEnvelopeNode(node)) return out
  if (node.kind === 'union') {
    out.push({ path, choices: node.members!, within })
    node.members!.forEach((member, index) =>
      unionsOf(member, path, [...within, { path, index, label: labelOf(member, index) }], out),
    )
  } else if (node.kind === 'array') unionsOf(node.element!, `${path}[]`, within, out)
  else if (node.kind === 'object')
    for (const [key, field] of Object.entries(node.fields!)) unionsOf(field, path ? `${path}.${key}` : key, within, out)
  return out
}

const labelOf = (choice: Node, index: number) =>
  choice.kind === 'literal' ? JSON.stringify(choice.value) : `choice ${index + 1}`

type Vector = { name: string; event: Record<string, unknown> }

export type ProtocolVectors = { comment: string; validator: unknown; valid: Vector[]; invalid: Vector[] }

export function buildVectors(): ProtocolVectors {
  const valid: Vector[] = []
  const invalid: Vector[] = []
  for (const member of members) {
    const type = typeOf(member)
    const full = sample(member, '', true) as Record<string, unknown>
    const minimal = sample(member, '', false) as Record<string, unknown>
    valid.push({ name: `${type} with every field`, event: full })
    valid.push({ name: `${type} with only its required fields`, event: minimal })
    // Every choice of every union, so a value one side drops (a send status, an error code)
    // shows up as an example the other side still has.
    for (const union of unionsOf(member, '')) {
      if (union.path === 'type') continue
      union.choices.forEach((choice, index) => {
        const path = [...union.within, { path: union.path, index, label: labelOf(choice, index) }]
        const event = sample(member, '', true, new Map(path.map((c) => [c.path, c.index]))) as Record<string, unknown>
        valid.push({ name: `${type} with ${path.map((c) => `${c.path} ${c.label}`).join(', ')}`, event })
      })
    }
    for (const [name, field] of Object.entries(member.fields!)) {
      if (name === 'type' || field.isOptional === 'optional') continue
      const { [name]: _missing, ...rest } = minimal
      invalid.push({ name: `${type} without ${name}`, event: rest })
    }
    // A field the protocol doesn't have is where plaintext could leave the bridge host.
    invalid.push({ name: `${type} with a field the protocol doesn't have`, event: { ...minimal, body: 'hello' } })
  }
  invalid.push({
    name: "an event type the protocol doesn't have",
    event: { seq: 0, type: 'secret', userId: 'userId-1', loginId: 'loginId-1', at: 0 },
  })
  return {
    comment:
      'Generated by packages/backend/scripts/write-protocol-schema.ts from the bridgeEvent validator. ' +
      'The backend accepts every valid event and refuses every invalid one; the bridge host must send each valid ' +
      'one back unchanged and never send an invalid one. `validator` is the validator itself, so that any change ' +
      'to it shows here.',
    validator: (bridgeEvent as unknown as { json: unknown }).json,
    valid,
    invalid,
  }
}
