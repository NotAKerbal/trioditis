// The bridge protocol's event schema and example events, built from the backend's
// `bridgeEvent` validator: the one description of what a bridge host may send. The Go bridge
// host embeds the schema (apps/bridge-host/internal/protocol/events.json) and checks itself
// against the examples, and the gateway's tests check the same examples against the
// validator, so a change on one side that the other doesn't have fails a test.
//
// scripts/write-protocol-schema.ts writes both files; test/protocol-schema.test.ts fails
// while they are out of date.

import { PROTOCOL_VERSION } from '@trioditis/core/bridge-protocol'
import { BRIDGE_EVENT_TYPES, MAX_SEALED_BYTES, bridgeEvent, envelope } from '../convex/validators.ts'

export const SCHEMA_FILE = '../../../apps/bridge-host/internal/protocol/events.json'
export const VECTORS_FILE = '../../../apps/bridge-host/internal/protocol/testdata/event-vectors.json'

/** The fields every event has, apart from the ones its type adds. */
const COMMON = ['seq', 'type', 'userId', 'loginId', 'at'] as const

/** A Convex validator, as far as walking one needs. */
type Node = {
  kind: string
  isOptional: 'optional' | 'required'
  fields?: Record<string, Node>
  members?: Node[]
  element?: Node
  value?: unknown
}

/**
 * `values` holds, for each field (by dotted path; `[]` steps into an array) that is one of a
 * set of values rather than any string or number, which values it may be.
 */
type EventShape = {
  required: string[]
  optional: string[]
  maxSealedBytes?: number
  values: Record<string, unknown[]>
}

export type ProtocolSchema = {
  comment: string
  version: number
  common: readonly string[]
  events: Record<string, EventShape>
}

const members = (bridgeEvent as unknown as Node).members!

function fieldsOf(member: Node) {
  return Object.entries(member.fields!).filter(([name]) => !(COMMON as readonly string[]).includes(name))
}

const typeOf = (member: Node) => member.fields!.type!.value as (typeof BRIDGE_EVENT_TYPES)[number]

/**
 * Records, by path, the values each field under `node` may take: a set of literals, or `any`
 * once some branch of a union lets it be anything else (a string, an object). The sets of all
 * of a union's branches are merged, so a value one branch allows is never refused.
 */
function collectValues(node: Node, path: string, into: Map<string, Set<unknown> | 'any'>) {
  if (node.kind === 'literal') {
    const values = into.get(path)
    if (values === undefined) into.set(path, new Set([node.value]))
    else if (values !== 'any') values.add(node.value)
    return
  }
  if (node.kind === 'union') {
    for (const member of node.members!) collectValues(member, path, into)
    return
  }
  into.set(path, 'any')
  if (node.kind === 'array') collectValues(node.element!, `${path}[]`, into)
  else if (node.kind === 'object' && !isEnvelopeNode(node))
    for (const [key, field] of Object.entries(node.fields!)) collectValues(field, `${path}.${key}`, into)
}

export function buildSchema(): ProtocolSchema {
  const events: Record<string, EventShape> = {}
  for (const member of members) {
    const type = typeOf(member)
    const fields = fieldsOf(member)
    const collected = new Map<string, Set<unknown> | 'any'>()
    for (const [name, field] of fields) collectValues(field, name, collected)
    const values: Record<string, unknown[]> = {}
    for (const [path, allowed] of collected) if (allowed !== 'any') values[path] = [...allowed]
    const shape: EventShape = {
      required: fields.filter(([, field]) => field.isOptional === 'required').map(([name]) => name),
      optional: fields.filter(([, field]) => field.isOptional === 'optional').map(([name]) => name),
      values,
    }
    const limit = (MAX_SEALED_BYTES as Record<string, number>)[type]
    if (limit !== undefined) shape.maxSealedBytes = limit
    events[type] = shape
  }
  return {
    comment:
      'Generated by packages/backend/scripts/write-protocol-schema.ts from the bridgeEvent validator. ' +
      'Do not edit: change packages/backend/convex/validators.ts and run `pnpm --filter @trioditis/backend protocol-schema`.',
    version: PROTOCOL_VERSION,
    common: COMMON,
    events,
  }
}

