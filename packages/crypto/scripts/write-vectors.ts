// Writes testdata/vectors.json: envelopes sealed by this package, which the Go
// implementation in apps/bridge-host must open. Recipient keys come from fixed seeds so the
// file only changes when the format does; the envelopes themselves are random each run.
// Run with `pnpm --filter @trioditis/crypto vectors` after changing the format.

import { writeFileSync } from 'node:fs'
import sodium from 'libsodium-wrappers'
import { encryptMedia, keyId, ready, sealJson, toBase64Url, type SealContext } from '../src/index.ts'

await ready()

function seeded(name: string) {
  const seed = sodium.crypto_generichash(32, sodium.from_string(`trioditis test vector ${name}`), null)
  const { publicKey, privateKey } = sodium.crypto_box_seed_keypair(seed)
  return { name, publicKey, privateKey }
}

const owner = seeded('owner')
const agent = seeded('agent-access')
const bridge = seeded('bridge')

const message: SealContext = { kind: 'message', ownerUserId: 'user_1', objectId: 'evt_abc' }
const outbound: SealContext = { kind: 'outbound', ownerUserId: 'user_1', objectId: 'cm_123' }
const chat: SealContext = { kind: 'chat', ownerUserId: 'user_1', objectId: 'whatsapp:123@s.whatsapp.net' }

const mediaBytes = sodium.from_string('not really a jpeg')
const media = encryptMedia(mediaBytes, 'user_1', 'media_1')

const vectors = {
  comment: 'Generated by packages/crypto/scripts/write-vectors.ts. See docs/architecture/sealing.md.',
  recipients: [owner, agent, bridge].map((key) => ({
    name: key.name,
    publicKey: toBase64Url(key.publicKey),
    privateKey: toBase64Url(key.privateKey),
    kid: keyId(key.publicKey),
  })),
  envelopes: [
    {
      name: 'message to owner and agent',
      context: message,
      recipients: ['owner', 'agent-access'],
      plaintext: { type: 'text', body: 'Hello from Trioditis 👋', mentions: [] },
      envelope: sealJson({ type: 'text', body: 'Hello from Trioditis 👋', mentions: [] }, [owner, agent], message),
    },
    {
      name: 'outbound to bridge',
      context: outbound,
      recipients: ['bridge'],
      plaintext: { type: 'text', body: 'Sent from the desktop app' },
      envelope: sealJson({ type: 'text', body: 'Sent from the desktop app' }, [bridge], outbound),
    },
    {
      name: 'chat metadata to owner',
      context: chat,
      recipients: ['owner'],
      plaintext: { name: 'Family', topic: '' },
      envelope: sealJson({ name: 'Family', topic: '' }, [owner], chat),
    },
  ],
  media: [
    {
      ownerUserId: 'user_1',
      mediaId: 'media_1',
      plaintext: toBase64Url(mediaBytes),
      ciphertext: toBase64Url(media.ciphertext),
      key: media.key,
      nonce: media.nonce,
    },
  ],
}

writeFileSync(new URL('../testdata/vectors.json', import.meta.url), JSON.stringify(vectors, null, 2) + '\n')
console.log('Wrote testdata/vectors.json')
